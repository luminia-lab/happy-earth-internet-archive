import assert from 'node:assert/strict';
import {readFile,stat} from 'node:fs/promises';
import {resolve} from 'node:path';
import vm from 'node:vm';
import {compile,csvRows} from './generate-airline-names.mjs';
const sample='iata_code;airline_name\nAC;Air Canada\nFI;"Icelandair; Example"\nD7;AirAsia X\n';
assert.equal(compile(sample).AC,'Air Canada');
assert.equal(compile(sample).FI,'Icelandair; Example');
assert.equal(csvRows('iata_code;airline_name\nQF;"Qantas ""Air"""\n')[1][1],'Qantas "Air"');
const path=resolve(import.meta.dirname,'../site/assets/data/airline-names.js'),sandbox={window:{}};
const source=await readFile(path,'utf8');
assert.ok((await stat(path)).size<200000);
vm.runInNewContext(source,sandbox);
const names=sandbox.window.AirlineNameIndex;
assert.ok(Object.keys(names).length>800);
assert.equal(names.AC,'Air Canada');
assert.match(names.FI,/Icelandair/i);
assert.match(names.D7,/AirAsia X/i);
for(const code of ['CI','NZ','QR','JQ','AA','LH'])assert.ok(names[code],code);
console.log('PASS offline airline names',Object.keys(names).length);
